"""Discord rich embed message formatter."""

from typing import Any, Dict, List, Optional
from app.utils.time import utc_now_iso
from app.config.settings import settings


# Centralized Standardized Discord Color Constants (Decimal)
COLOR_ASSIGNMENT = 3066993      # #2ECC71 - Green (Assignment to me)
COLOR_NOTIFICATION = 3447003    # #3498DB - Blue (Mention / General notification)
COLOR_WORKLOG = 10181046        # #9B59B6 - Purple (Worklog / Reports)
COLOR_OVERDUE = 15158332        # #E74C3C - Red (Overdue, Blocked, Errors)
COLOR_ATTENTION = 15844367      # #F1C40F - Yellow (PM Attention, Stale, Warnings)
COLOR_TICKET_CREATED = 14689374 # #E0245E - Dark Pink / Red (Ticket Creation Notifications)

# Backwards compatibility aliases
COLOR_GREEN = COLOR_ASSIGNMENT
COLOR_BLUE = COLOR_NOTIFICATION
COLOR_PURPLE = COLOR_WORKLOG
COLOR_RED = COLOR_OVERDUE
COLOR_AMBER = COLOR_ATTENTION
COLOR_MAGENTA = COLOR_ATTENTION
COLOR_DARK_PINK = COLOR_TICKET_CREATED



class DiscordFormatter:
    """Formats notifications and events into Discord Webhook embed payloads."""

    @staticmethod
    def format_jira_link(task_key: str, label: Optional[str] = None) -> str:
        """Construct a clickable markdown link for Jira issues."""
        url = settings.get_jira_browse_url(task_key)
        display_label = label or task_key
        return f"[{display_label}]({url})"

    @staticmethod
    def format_embed(
        title: str,
        description: str,
        color: int = COLOR_BLUE,
        fields: Optional[List[Dict[str, Any]]] = None,
        footer_text: str = "Generated by PM Operations Agent",
        timestamp: Optional[str] = None,
        url: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Construct a Discord Webhook payload with a rich embed."""
        embed: Dict[str, Any] = {
            "title": title,
            "description": description,
            "color": color,
            "footer": {"text": footer_text},
            "timestamp": timestamp or utc_now_iso()
        }
        if url:
            embed["url"] = url
        if fields:
            embed["fields"] = fields

        return {"embeds": [embed]}

    @classmethod
    def format_status_reply(cls, issue_data: Dict[str, Any]) -> str:
        """Format a concise plain-text/markdown status reply for /pm status."""
        key = issue_data.get("key", "")
        fields = issue_data.get("fields", {})
        summary = fields.get("summary", "Untitled")
        status_name = fields.get("status", {}).get("name", "Unknown") if isinstance(fields.get("status"), dict) else str(fields.get("status") or "Unknown")
        assignee_data = fields.get("assignee")
        if isinstance(assignee_data, dict):
            assignee_name = assignee_data.get("displayName", "Unassigned")
        else:
            assignee_name = str(assignee_data or "Unassigned")
        priority_data = fields.get("priority")
        if isinstance(priority_data, dict):
            priority_name = priority_data.get("name", "None")
        else:
            priority_name = str(priority_data or "None")
        due_date = fields.get("duedate") or fields.get("due_date") or "None"

        return (
            f"📋 **{key}**: {summary}\n"
            f"• **Status:** {status_name}\n"
            f"• **Assignee:** {assignee_name}\n"
            f"• **Priority:** {priority_name}\n"
            f"• **Due:** {due_date}"
        )

    @classmethod
    def format_workflow_violation(
        cls,
        task_key: str,
        task_title: str,
        resource_name: str,
        project_name: str,
        details: str,
        timestamp: Optional[str] = None
    ) -> Dict[str, Any]:
        """Format a PM workflow violation alert."""
        issue_link = cls.format_jira_link(task_key)
        jira_url = settings.get_jira_browse_url(task_key)
        fields = [
            {"name": "Issue", "value": issue_link, "inline": True},
            {"name": "Project", "value": project_name or "N/A", "inline": True},
            {"name": "Resource", "value": resource_name or "Unassigned", "inline": True},
            {"name": "Title", "value": task_title or "Untitled", "inline": False},
            {"name": "Issue Details", "value": details, "inline": False},
        ]
        return cls.format_embed(
            title=f"🚨 Jira Workflow Alert — {task_key}",
            description=f"Activity detected on {issue_link} while remaining in **To Do**.",
            color=COLOR_RED,
            fields=fields,
            timestamp=timestamp,
            url=jira_url
        )

