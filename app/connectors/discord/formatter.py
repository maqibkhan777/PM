    @classmethod
    def _chunk_embed_lines(
        cls,
        title_base: str,
        lines: List[str],
        footer_text: str = "Generated by PM Operations Agent",
        max_total_budget: int = 5800,
        max_embed_desc_len: int = 3800,
        max_embeds: int = 10,
        color: int = COLOR_PURPLE,
    ) -> Dict[str, Any]:
        """Chunk a sequence of lines across up to max_embeds, strictly enforcing cumulative and per-embed limits."""
        embeds: List[Dict[str, Any]] = []
        current_chunk_lines: List[str] = []
        current_chunk_len = 0
        cumulative_budget = 0
        part = 1
        footer_len = len(footer_text)

        for line in lines:
            line_len = len(line) + (1 if current_chunk_lines else 0)
            current_title = title_base if part == 1 else f"{title_base} (Part {part})"
            title_footer_overhead = len(current_title) + footer_len

            would_exceed_embed = (current_chunk_len + line_len > max_embed_desc_len)
            would_exceed_budget = (cumulative_budget + current_chunk_len + line_len + title_footer_overhead > max_total_budget)

            if (would_exceed_embed or would_exceed_budget) and current_chunk_lines:
                desc = "\n".join(current_chunk_lines)
                embeds.append({
                    "title": current_title,
                    "description": desc,
                    "color": color,
                    "footer": {"text": footer_text}
                })
                cumulative_budget += len(current_title) + len(desc) + footer_len
                part += 1
                current_chunk_lines = [line]
                current_chunk_len = len(line)

                if len(embeds) >= max_embeds:
                    break
            else:
                current_chunk_lines.append(line)
                current_chunk_len += line_len

        if current_chunk_lines and len(embeds) < max_embeds:
            current_title = title_base if part == 1 else f"{title_base} (Part {part})"
            desc = "\n".join(current_chunk_lines)
            embeds.append({
                "title": current_title,
                "description": desc,
                "color": color,
                "footer": {"text": footer_text}
            })

        return {"embeds": embeds[:max_embeds]}

